import httpx
import logging
from typing import Dict, Any, List
from app.core.config import settings
from app.services.embeddings import EmbeddingService
from app.core.database import search_similar_chunks

logger = logging.getLogger("nyayaflow.ai.rag_engine")

DISCLAIMER_TEXT = "This analysis is generated by NyayaFlow AI from retrieved case records for informational assistance. It does not constitute formal legal counsel."

class RAGEngine:
    @staticmethod
    async def answer_query(
        query: str,
        case_id: str,
        document_id: str = None,
        top_k: int = 4,
        model: str = None
    ) -> Dict[str, Any]:
        """
        Executes grounded RAG workflow:
        1. Query embedding -> 2. Vector search in pgvector -> 3. Context assembly -> 4. Grounded synthesis -> 5. Citations
        """
        provider = (settings.LLM_PROVIDER or "groq").lower()

        # Resolve active model based on provider
        if provider == "groq":
            # If a model is explicitly passed and is not an ollama local prefix, use it
            if model and not any(model.startswith(m) for m in ["qwen2.5", "llama3.2", "llama3", "mistral"]):
                active_model = model
            else:
                active_model = settings.GROQ_MODEL
        else:
            active_model = model or settings.OLLAMA_MODEL

        # 1. Generate query embedding (384-dim)
        query_vector = EmbeddingService.encode(query)

        # 2. Retrieve top-k chunks via vector cosine distance
        chunks = search_similar_chunks(
            query_embedding=query_vector,
            case_id=case_id,
            document_id=document_id,
            top_k=top_k
        )

        # Format citations
        citations = []
        retrieved_ids = []
        for c in chunks:
            citations.append({
                "document_id": c["document_id"],
                "document_title": c["document_title"],
                "file_name": c["file_name"],
                "page_number": c["page_number"],
                "excerpt": c["content"][:250] + ("..." if len(c["content"]) > 250 else ""),
                "similarity_score": c["similarity_score"]
            })
            retrieved_ids.append(c["chunk_id"])

        # If no chunks were retrieved (empty case or query unrelated)
        if not chunks:
            return {
                "answer": "The case records do not contain any relevant documents or excerpts to address this inquiry. Please ensure that relevant legal filings or orders have been uploaded to this case.",
                "citations": [],
                "retrieved_chunk_ids": [],
                "confidence": "low",
                "disclaimer": DISCLAIMER_TEXT
            }

        # 3. Assemble Prompt with strict grounding
        context_blocks = []
        for i, c in enumerate(chunks, start=1):
            context_blocks.append(
                f"[Source {i}: {c['document_title']} | Page {c['page_number']}]\n{c['content']}"
            )
        formatted_context = "\n\n".join(context_blocks)

        system_instruction = (
            "You are NyayaFlow, an elite legal intelligence assistant. "
            "Your task is to answer the user's question accurately and objectively using ONLY the provided case document excerpts. "
            "CRITICAL INSTRUCTIONS:\n"
            "1. You must cite the specific document title and page number for every assertion you make.\n"
            "2. Never fabricate citations, section numbers, case laws, or dates not in the excerpts.\n"
            "3. If the excerpts do not contain sufficient facts to answer the question, clearly state: "
            "'The provided document excerpts do not contain sufficient information to answer this question.'\n"
            "4. Do not offer legal opinions beyond what is documented in the texts."
        )

        user_prompt = f"""DOCUMENT EXCERPTS:
{formatted_context}

USER QUESTION:
{query}

GROUNDED LEGAL ANSWER:"""

        # 4. Attempt synthesis via configured provider
        synthesis_response = None
        used_model = active_model

        if provider == "groq":
            synthesis_response = await RAGEngine._query_groq(
                system_instruction=system_instruction,
                prompt=user_prompt,
                model=active_model
            )
            # If Groq synthesis fails, fallback to local Ollama if reachable
            if not synthesis_response:
                logger.info("Groq synthesis unavailable; attempting local Ollama fallback...")
                synthesis_response = await RAGEngine._query_ollama(
                    system_instruction=system_instruction,
                    prompt=user_prompt,
                    model=settings.OLLAMA_MODEL
                )
                if synthesis_response:
                    used_model = f"{settings.OLLAMA_MODEL} (Ollama Fallback)"
        else:
            # Local Ollama provider
            synthesis_response = await RAGEngine._query_ollama(
                system_instruction=system_instruction,
                prompt=user_prompt,
                model=active_model
            )

        if synthesis_response:
            return {
                "answer": synthesis_response,
                "citations": citations,
                "retrieved_chunk_ids": retrieved_ids,
                "confidence": "high",
                "model_used": used_model,
                "disclaimer": DISCLAIMER_TEXT
            }

        # 5. Deterministic fallback grounded synthesis
        fallback_answer = RAGEngine._grounded_fallback_synthesis(query, chunks)
        return {
            "answer": fallback_answer,
            "citations": citations,
            "retrieved_chunk_ids": retrieved_ids,
            "confidence": "medium",
            "model_used": "NyayaFlow Local Grounded Synthesizer",
            "disclaimer": DISCLAIMER_TEXT
        }

    @staticmethod
    async def _query_groq(system_instruction: str, prompt: str, model: str) -> str:
        """
        Executes ultra-fast synthesis via Groq Cloud OpenAI-compatible API.
        """
        if not settings.GROQ_API_KEY:
            logger.warning("GROQ_API_KEY is not configured. Cannot query Groq.")
            return None
        try:
            headers = {
                "Authorization": f"Bearer {settings.GROQ_API_KEY}",
                "Content-Type": "application/json"
            }
            payload = {
                "model": model,
                "messages": [
                    {"role": "system", "content": system_instruction},
                    {"role": "user", "content": prompt}
                ],
                "temperature": 0.1,
                "top_p": 0.9,
                "max_completion_tokens": 2048
            }
            async with httpx.AsyncClient(timeout=45.0) as client:
                res = await client.post(
                    f"{settings.GROQ_BASE_URL}/chat/completions",
                    headers=headers,
                    json=payload
                )
                if res.status_code == 200:
                    data = res.json()
                    choices = data.get("choices", [])
                    if choices:
                        answer = choices[0].get("message", {}).get("content", "").strip()
                        if answer:
                            return answer
                elif res.status_code == 404:
                    logger.warning(f"Groq model '{model}' not found. Details: {res.text}")
                else:
                    logger.warning(f"Groq returned HTTP {res.status_code}: {res.text}")
        except httpx.ConnectError:
            logger.warning(f"Could not connect to Groq at {settings.GROQ_BASE_URL}.")
        except httpx.TimeoutException:
            logger.warning(f"Groq generation timed out for model '{model}'.")
        except Exception as e:
            logger.warning(f"Groq RAG synthesis error: {e}")
        return None

    @staticmethod
    async def _query_ollama(system_instruction: str, prompt: str, model: str) -> str:
        try:
            full_prompt = f"{system_instruction}\n\n{prompt}"
            async with httpx.AsyncClient(timeout=45.0) as client:
                res = await client.post(
                    f"{settings.OLLAMA_BASE_URL}/api/generate",
                    json={
                        "model": model,
                        "prompt": full_prompt,
                        "stream": False,
                        "options": {
                            "temperature": 0.1,
                            "top_p": 0.9
                        }
                    }
                )
                if res.status_code == 200:
                    data = res.json()
                    answer = data.get("response", "").strip()
                    if answer:
                        return answer
                elif res.status_code == 404:
                    logger.warning(f"Ollama model '{model}' not found. Please run 'ollama pull {model}'. Details: {res.text}")
                else:
                    logger.warning(f"Ollama returned HTTP {res.status_code}: {res.text}")
        except httpx.ConnectError:
            logger.warning(f"Could not connect to Ollama at {settings.OLLAMA_BASE_URL}. Is 'ollama serve' running?")
        except httpx.TimeoutException:
            logger.warning(f"Ollama generation timed out for model '{model}'.")
        except Exception as e:
            logger.warning(f"Ollama RAG synthesis error: {e}")
        return None

    @staticmethod
    def _grounded_fallback_synthesis(query: str, chunks: List[Dict[str, Any]]) -> str:
        """
        Synthesizes an honest, grounded reply directly citing the highest-ranked chunk excerpts.
        """
        top_chunk = chunks[0]
        page_num = top_chunk["page_number"]
        doc_title = top_chunk["document_title"]
        excerpt = top_chunk["content"].strip()

        # Format excerpt for readability
        lines = [line.strip() for line in excerpt.split("\n") if line.strip()]
        lead_statement = lines[0] if lines else excerpt[:150]

        response = (
            f"Based on **{doc_title}** *(Page {page_num})*:\n\n"
            f"> \"{lead_statement}\"\n\n"
            f"The retrieved case filing specifies that:\n"
            f"- **Source Reference**: {doc_title}, Page {page_num}\n"
            f"- **Supporting Excerpt**: {excerpt[:280]}...\n\n"
        )

        if len(chunks) > 1:
            second_chunk = chunks[1]
            response += (
                f"Additionally, in **{second_chunk['document_title']}** *(Page {second_chunk['page_number']})*, "
                f"the record notes:\n"
                f"> \"{second_chunk['content'][:200]}...\"\n"
            )

        return response
